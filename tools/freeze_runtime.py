"""Write runtime/constraints.txt: the exact versions of everything the AI parts need, taken from the
dev venv where they are tested. The portable app's Set up window installs with these pins, so a
user gets the same versions as the developer.

    .venv\\Scripts\\python.exe tools\\freeze_runtime.py
"""
from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
REQS = ROOT / "runtime" / "requirements.txt"
OUT = ROOT / "runtime" / "constraints.txt"
# installed by their own Set up steps (or pre-installed with the portable)
EXTRA_ROOTS = ["torch", "torchaudio", "PySide6-Essentials", "requests", "pip"]
NOT_PINNED = {"chatterbox-tts", "en-core-web-sm"}


def closure(roots: list[str]) -> dict[str, str]:
    env = default_environment()
    seen: dict[str, str] = {}
    visited: set[tuple[str, frozenset]] = set()
    todo: list[tuple[str, frozenset]] = [(Requirement(r).name, frozenset(Requirement(r).extras)) for r in roots]
    while todo:
        name, extras = todo.pop()
        key = canonicalize_name(name)
        if (key, extras) in visited:
            continue
        visited.add((key, extras))
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            raise SystemExit(f"{name} is not installed in this venv")
        seen[key] = dist.version
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker and not any(req.marker.evaluate({**env, "extra": e}) for e in (extras or {""})):
                continue
            todo.append((req.name, frozenset(req.extras)))
    return seen


def main() -> None:
    roots = [ln.split("#")[0].strip() for ln in REQS.read_text(encoding="utf-8").splitlines()]
    roots = [r for r in roots if r and not r.startswith("-")] + EXTRA_ROOTS
    pins = closure(roots)
    lines = ["# Generated by tools/freeze_runtime.py from the dev venv - do not edit by hand.",
             f"# Python {sys.version.split()[0]}"]
    for key in sorted(pins):
        if key in NOT_PINNED:
            continue
        version = re.sub(r"\+.*$", "", pins[key])        # torch 2.11.0+cu128 -> 2.11.0 (matches cu128 and cpu)
        lines.append(f"{key}=={version}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(lines) - 2} packages")


if __name__ == "__main__":
    main()
